function [mse_rand] = random_sampling(filter, data_vec, n, inv_prior, mu, ...
    sigma,slack_idx, parameter, x_0, num_of_iterations_random_sampling, ...
    number_of_measured_buses_array)
            y_data_rand = zeros(num_of_iterations_random_sampling, length(number_of_measured_buses_array));
            for p=1:num_of_iterations_random_sampling
                sampling_set_rand = randperm(n); % Random sampling method
                % Random sampling
                fprintf('start calculate the MSE for random sampling \n')
                [y_data_rand(p,:)] = evalute_sampling_set( ...
                    number_of_measured_buses_array, sampling_set_rand, ...
                    filter, data_vec, n, inv_prior, mu, sigma, slack_idx, ...
                    parameter, x_0);
            end
            mse_rand = mean(y_data_rand, 1);
end